"""Cosine similarity calculator for sparse vector retrieval.

Calculates the cosine similarity between L2-normalized sparse vector representations
(such as those generated by TfidfCalculator). Because the input vectors are already
unit-length (L2-normalized), the cosine similarity reduces to the dot product of
weights for terms common to both vectors:

    similarity = sum(query_vector[t] * document_vector[t] for t in common_terms)

Inputs are strictly validated:
- Must be dictionaries with non-empty string keys.
- Values must be finite, non-negative numbers (booleans rejected).
- Returns 0.0 for empty vectors or vectors with disjoint vocabularies.
- Does not mutate input dictionaries.
- Does not silently clamp calculated similarity scores.
"""

from __future__ import annotations

import math
from typing import Mapping


def _validate_vector(vector: Mapping[str, float], param_name: str) -> None:
    """Validate that vector is a valid sparse vector mapping.

    Args:
        vector: Vector mapping to validate.
        param_name: Parameter name for descriptive error messages.

    Raises:
        TypeError: If vector is not a dict, keys are not strings, or values are
            booleans or non-numeric types.
        ValueError: If keys are empty strings, or values are negative, NaN, or infinite.
    """
    if not isinstance(vector, dict):
        raise TypeError(f"{param_name} must be a dict, got {type(vector).__name__}")

    for key, value in vector.items():
        if not isinstance(key, str):
            raise TypeError(
                f"All keys in {param_name} must be str, got {type(key).__name__}"
            )
        if len(key) == 0:
            raise ValueError(f"Keys in {param_name} cannot be empty strings")

        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise TypeError(
                f"All values in {param_name} must be numeric (int or float), got {type(value).__name__}"
            )
        if not math.isfinite(value):
            raise ValueError(f"Values in {param_name} must be finite numbers, got {value}")
        if value < 0.0:
            raise ValueError(f"Values in {param_name} must be non-negative, got {value}")


class CosineSimilarity:
    """Calculates cosine similarity between L2-normalized sparse vectors."""

    def similarity(
        self,
        query_vector: dict[str, float],
        document_vector: dict[str, float],
    ) -> float:
        """Calculate cosine similarity between two L2-normalized sparse vectors.

        Computes the dot product over the intersection of terms in both vectors.
        Because inputs are assumed to be L2-normalized, no additional normalization
        is applied.

        Args:
            query_vector: Sparse term-to-weight dictionary for query.
            document_vector: Sparse term-to-weight dictionary for document.

        Returns:
            The dot product similarity as a float, or 0.0 if either vector is empty
            or if the vectors share no common terms.

        Raises:
            TypeError: If either input is not a dict, has non-string keys, or
                contains boolean or non-numeric values.
            ValueError: If keys are empty strings, or values are negative, NaN,
                or infinite.
        """
        _validate_vector(query_vector, "query_vector")
        _validate_vector(document_vector, "document_vector")

        if not query_vector or not document_vector:
            return 0.0

        # Iterate over the smaller vector to minimize hash lookups
        if len(query_vector) <= len(document_vector):
            smaller, larger = query_vector, document_vector
        else:
            smaller, larger = document_vector, query_vector

        dot_product = sum(
            weight * larger[term]
            for term, weight in smaller.items()
            if term in larger
        )

        return float(dot_product)


def cosine_similarity(
    query_vector: dict[str, float],
    document_vector: dict[str, float],
) -> float:
    """Convenience function to compute cosine similarity between two sparse vectors."""
    return CosineSimilarity().similarity(query_vector, document_vector)
